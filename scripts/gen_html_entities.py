"""Regenerate src/html_entities.hpp from the HTML5 named character references
(Python's html.entities.html5, which mirrors https://html.spec.whatwg.org/entities.json).

    python scripts/gen_html_entities.py > src/html_entities.hpp
"""
from html.entities import html5

# Octal escapes (max 3 digits) so a following hex-looking letter can't be
# swallowed, which "\xNN" escapes would do in C++.
def lit(s: str) -> str:
    return "".join(f"\\{b:03o}" for b in s.encode("utf-8"))

items = sorted(html5.items(), key=lambda kv: kv[0].encode("ascii"))
print("// Generated by scripts/gen_html_entities.py -- do not edit.")
print("// HTML5 named character references; keys keep their trailing ';' when they")
print("// have one, and the legacy ones that are valid without it appear without.")
print("#pragma once")
print("#include <cstddef>")
print("#include <cstring>")
print("namespace pygixml_html {")
print("struct Entity { const char* name; const char* value; };")
print("static const Entity kEntities[] = {")
for k, v in items:
    print(f'    {{"{k}", "{lit(v)}"}},')
print("};")
print(f"static const size_t kEntityCount = {len(items)};")
print("""
// Binary search; `name` is not NUL-terminated.
static inline const char* entity_lookup(const char* name, size_t len) {
    size_t lo = 0, hi = kEntityCount;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        const char* k = kEntities[mid].name;
        int c = std::strncmp(k, name, len);
        if (c == 0) c = k[len] == '\\0' ? 0 : 1;   // k longer than name sorts after it
        if (c == 0) return kEntities[mid].value;
        if (c < 0) lo = mid + 1; else hi = mid;
    }
    return nullptr;
}
}  // namespace pygixml_html""")
