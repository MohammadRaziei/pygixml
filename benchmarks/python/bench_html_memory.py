"""
bench_html_memory.py: peak memory of HTML parsing, pygixml.parse_html against the
libraries bench_html.py compares it with. Writes html_memory.json in the shape of
throughput_memory.json ({operation: [{genre, size, bytes, libraries: {...}}]}), so the
report renders it next to the speed charts.

The pages are the same ones bench_html.py times. They are generated by a short-lived
child (--make) and handed to one fresh worker per (page, library) as a file path, so this
driver never holds a page in memory (see bench_op_memory_driver.py for why that matters).
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKER = HERE / "bench_html_memory_one.py"
LIBRARIES = ["pygixml", "lxml", "bs4_html_parser", "bs4_lxml", "html5lib", "selectolax"]


def make_pages(directory):
    sys.path.insert(0, str(HERE))
    from bench_html import GENRES, SIZES, make_page
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for genre in GENRES:
        for size, target in SIZES.items():
            (directory / f"{genre}__{size}.html").write_text(make_page(genre, target), encoding="utf-8")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("output", nargs="?", help="path to write html_memory.json")
    p.add_argument("--make", metavar="DIR", help="only write the pages to DIR (used by this script itself)")
    p.add_argument("--scratch", default=None, help="directory for the generated pages (default: next to the output)")
    args = p.parse_args()
    if args.make:
        make_pages(args.make)
        return
    if not args.output:
        p.error("output is required")

    scratch = Path(args.scratch) if args.scratch else Path(args.output).resolve().parent / "_html_pages"
    subprocess.run([sys.executable, str(Path(__file__).resolve()), "--make", str(scratch)], check=True)

    rows = []
    for page in sorted(scratch.glob("*.html")):
        genre, size = page.stem.split("__")
        row = {"genre": genre, "size": size, "bytes": page.stat().st_size, "libraries": {}}
        for lib in LIBRARIES:
            out = subprocess.run([sys.executable, str(WORKER), lib, str(page)], capture_output=True, text=True)
            try:
                row["libraries"][lib] = json.loads(out.stdout.strip().splitlines()[-1])
            except (ValueError, IndexError):
                row["libraries"][lib] = {"operation": "html_parse", "library": lib, "available": False,
                                         "error": (out.stderr or "no output").strip()[-200:]}
            print(f"bench_html_memory: {genre}/{size} {lib}", file=sys.stderr)
        rows.append(row)
        page.unlink()
    try:
        scratch.rmdir()
    except OSError:
        pass
    with open(args.output, "w", encoding="utf-8") as f:
        json.dump({"html_parse": rows}, f, indent=2)
    print(f"bench_html_memory: {len(rows)} pages -> {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
